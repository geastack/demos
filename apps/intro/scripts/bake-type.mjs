// Bakes the intro's lines of type into src/data/type.ts as 4-bit coverage
// masks, rendered from the brand TTFs in shared/fonts. The intro blends them
// into its frame itself, in any colour or gradient, so the type needs no font
// atlas and the canvas stays a single straight-to-display image.
//
// Hanken Grotesk ExtraBold with the brand's tight -0.035em tracking for the
// name and tagline, JetBrains Mono uppercase with 0.12em for the kickers.
//
// Run from the app folder: `npm run type`.

import { writeFile } from "node:fs/promises";
import sharp from "sharp";

const OUTPUT = "src/data/type.ts";
const HANKEN = { file: "../../shared/fonts/HankenGrotesk-ExtraBold.ttf", name: "Hanken Grotesk ExtraBold" };
const MONO = { file: "../../shared/fonts/JetBrainsMono-Medium.ttf", name: "JetBrains Mono Medium" };
const DPI = 96; // so 1 pt is 4/3 px
const PANGO_UNITS = 1024 * 0.75; // letter_spacing units per px

// [constant name, text, face, size px, tracking em, typed]: a typed line
// also gets STOPS, the columns its first n characters cover.
const LINES = [
  ["COMMAND", "> GEA FLASH --BOARD DISCO", MONO, 11, 0.12, true],
  ["STATUS", "OK  STM32F746 · CORTEX-M7 · 200 MHZ · NO GPU", MONO, 11, 0.12, true],
  ["NAME", "GeaStack", HANKEN, 28, -0.035],
  ["LEAD", "Write TypeScript.", HANKEN, 16, -0.035],
  ["STRONG", "Build native apps.", HANKEN, 16, -0.035],
];

const escape = (text) => text.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;");

// Coverage 0..15 per pixel, plus the mask's size. Masks are cropped to the
// ink.
async function render(text, face, size, tracking) {
  const spacing = Math.round(tracking * size * PANGO_UNITS);
  const { data, info } = await sharp({
    text: {
      text: `<span letter_spacing="${spacing}">${escape(text)}</span>`,
      font: `${face.name} ${size * 0.75}`,
      fontfile: face.file,
      dpi: DPI,
      rgba: true,
    },
  })
    .raw()
    .toBuffer({ resolveWithObject: true });
  let digits = "";
  for (let i = 0; i < info.width * info.height; i++) digits += Math.round((data[i * 4 + 3] * 15) / 255).toString(16);
  return { width: info.width, height: info.height, digits };
}

// The columns each prefix of a typed line covers: its ink's right edge, as
// every prefix's mask starts at the same first glyph.
async function stops(text, face, size, tracking) {
  const out = [0];
  for (let n = 1; n <= text.length; n++) {
    const prefix = text.slice(0, n).trimEnd();
    out.push(prefix ? (await render(prefix, face, size, tracking)).width : 0);
  }
  return out;
}

// The space between the tagline's two halves, as set in one line.
const whole = await render("Write TypeScript. Build native apps.", HANKEN, 16, -0.035);
const lead = await render("Write TypeScript.", HANKEN, 16, -0.035);
const strong = await render("Build native apps.", HANKEN, 16, -0.035);

let source = `// Generated by scripts/bake-type.mjs from the brand fonts. Do not edit.
// Each line of type is a width x height coverage mask, one hex digit (0..15)
// per pixel, row by row, cropped to the ink.

export const TAGLINE_GAP = ${whole.width - lead.width - strong.width};
`;
for (const [name, text, face, size, tracking, typed] of LINES) {
  const mask = await render(text, face, size, tracking);
  const rows = mask.digits.match(/.{1,110}/g);
  source += `
// "${text}"
export const ${name}_WIDTH = ${mask.width};
export const ${name}_HEIGHT = ${mask.height};
export const ${name}_MASK = [
${rows.map((row) => `  "${row}",`).join("\n")}
];
`;
  if (typed) source += `export const ${name}_STOPS = [${(await stops(text, face, size, tracking)).join(", ")}];\n`;
}
await writeFile(OUTPUT, source);
console.log(`baked ${LINES.length} lines into ${OUTPUT}`);
